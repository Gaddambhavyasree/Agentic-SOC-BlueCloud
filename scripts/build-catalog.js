#!/usr/bin/env node
/**
 * build-catalog.js
 *
 * Generates docs/DASHBOARD-CATALOG.md from the exported dashboards + the live
 * panel validation results, so the catalog can never drift from the JSON.
 *
 * Usage: node scripts/build-catalog.js
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const DASH_DIR = path.join(ROOT, 'dashboards');
const EXP_DIR = path.join(ROOT, 'export');
const DOC_DIR = path.join(ROOT, 'docs');

const readJson = (p) => JSON.parse(fs.readFileSync(p, 'utf8').replace(/^\uFEFF/, ''));
const inventory = readJson(path.join(EXP_DIR, 'inventory.json'));
const dsByUid = new Map(inventory.datasources.map((d) => [d.uid, d]));

const validation = fs.existsSync(path.join(EXP_DIR, 'panel-validation.json'))
  ? readJson(path.join(EXP_DIR, 'panel-validation.json'))
  : { results: [] };
const valByPanel = new Map();
for (const r of validation.results) {
  if (r.status === 'static') continue;
  const key = `${r.uid}::${r.panelId}`;
  if (!valByPanel.has(key)) valByPanel.set(key, []);
  valByPanel.get(key).push(r);
}

// What each dashboard is for - the operational question it answers.
const PURPOSE = {
  'SOC Overview': 'How much is happening, and how bad is it? (alert volume + severity)',
  'Threat Detection': 'What is the network intrusion detection telling us? (Suricata + MITRE ATT&CK)',
  'File Integrity': 'What changed on the endpoints? (FIM - modified / added / deleted files and registry keys)',
  'Vulnerabilities': 'What is known-broken on the estate? (vulnerability detector alerts, severity, CVE, package)',
  'Brute Force & Active Response': 'Who is trying to get in, and did we respond? (authentication failures + active response)',
  'Configuration Assessment': 'Does the estate meet its security baseline? (CIS / SCA check results)',
};

const ORDER = ['SOC Overview', 'Threat Detection', 'File Integrity', 'Vulnerabilities', 'Brute Force & Active Response', 'Configuration Assessment'];

const files = fs.readdirSync(DASH_DIR).filter((f) => f.endsWith('.json')).sort();
const dashes = files.map((f) => {
  const raw = readJson(path.join(DASH_DIR, f));
  const d = raw.dashboard || raw;
  const url = (raw.meta && raw.meta.url) || `/d/${d.uid}`;
  d.__slug = url.split('/').filter(Boolean).pop() || d.uid;
  return d;
});
dashes.sort((a, b) => {
  const ai = ORDER.indexOf((a.title || '').trim());
  const bi = ORDER.indexOf((b.title || '').trim());
  return (ai < 0 ? 99 : ai) - (bi < 0 ? 99 : bi);
});

const md = [];
md.push('# Dashboard Catalog');
md.push('');
md.push('Generated by `scripts/build-catalog.js` from the exported dashboard JSON + the live validation run.');
md.push('');
md.push('> Screenshots are captured from the live instance by `scripts/capture-screenshots.js`. They contain live');
md.push('> telemetry (host names, source IPs, rule text) - see the data-hygiene note in the README.');
md.push('');
md.push('| # | Dashboard | Operational question it answers | UID | Panels | Default range | Live rows |');
md.push('|---|---|---|---|---|---|---|');
dashes.forEach((d, i) => {
  const title = (d.title || '').trim();
  const rows = validation.results
    .filter((r) => r.uid === d.uid && r.status !== 'static')
    .reduce((n, r) => n + (r.rows || 0), 0);
  md.push(
    `| ${i + 1} | **${title}** | ${PURPOSE[title] || '-'} | \`${d.uid}\` | ${(d.panels || []).length} | ${d.time ? `${d.time.from} → ${d.time.to}` : '-'} | ${rows || '-'} |`
  );
});
md.push('');
md.push('---');
md.push('');

for (const d of dashes) {
  const title = (d.title || '').trim();
  const meta = inventory.dashboards.find((x) => x.uid === d.uid) || {};
  const slug = d.__slug;
  const shot = `screenshots/${d.uid}__${slug}.png`;
  const hasShot = fs.existsSync(path.join(DOC_DIR, shot));
  md.push(`## ${title}`);
  md.push('');
  if (hasShot) {
    md.push(`![${title}](${shot})`);
    md.push('');
  }
  md.push(`- **UID:** \`${d.uid}\`  |  **Grafana URL:** ${meta.url || `\/d\/${d.uid}`}`);
  md.push(`- **Question:** ${PURPOSE[title] || '-'}`);
  md.push(`- **Default time range:** ${d.time ? `${d.time.from} → ${d.time.to}` : '-'}   |  **Auto-refresh:** ${d.refresh || 'none'}`);
  md.push(`- **Panels:** ${(d.panels || []).length}   |  **Last edited (server):** ${meta.updated || '-'}`);
  const ds = (d.panels || []).map((p) => p.datasource && p.datasource.uid).filter(Boolean);
  const dsNames = [...new Set(ds)].map((u) => (dsByUid.get(u) ? dsByUid.get(u).name : u));
  md.push(`- **Datasource:** ${dsNames.join(', ') || '-'} (index \`${(dsByUid.get(ds[0]) || {}).indexPattern || '-'}\`)`);
  md.push('');
  md.push('| # | Panel | Type | Query | Aggregations | Fields used | Live rows |');
  md.push('|---|---|---|---|---|---|---|');
  for (const p of d.panels || []) {
    const targets = p.targets || [];
    const q = targets.length
      ? targets.map((t) => `\`${t.query}\``).join('<br>')
      : p.type === 'text'
        ? '_(branding banner)_'
        : '—';
    const aggs = targets
      .flatMap((t) => (t.bucketAggs || []).map((b) => `${b.type}: \`${b.field}\``))
      .concat(targets.flatMap((t) => (t.metrics || []).filter((m) => m.field).map((m) => `metric:${m.field}`)))
      .join('<br>') || '—';
    const fields = [
      ...new Set(
        targets
          .flatMap((t) => (t.metrics || []).map((m) => m.field))
          .concat(targets.flatMap((t) => (t.bucketAggs || []).map((b) => b.field)))
          .filter(Boolean)
      ),
    ].map((f) => `\`${f}\``).join(', ') || '—';
    const rows = (valByPanel.get(`${d.uid}::${p.id}`) || []).reduce((n, r) => n + (r.rows || 0), 0);
    const rowsCell = targets.length ? (rows || '0') : '—';
    md.push(`| ${p.id} | ${p.title || '_(untitled)_'} | ${p.type} | ${q} | ${aggs} | ${fields} | ${rowsCell} |`);
  }
  md.push('');
  const empties = (valByPanel.get(`${d.uid}`) || []);
  md.push('');
}

md.push('---');
md.push('');
md.push('## Field reference');
md.push('');
md.push('Every field referenced by these dashboards, and whether it exists in the live `wazuh-alerts-4.x-*` mapping.');
md.push('');
md.push('| Field | Used by panels |');
md.push('|---|---|');
const usage = new Map();
for (const d of dashes) {
  for (const p of d.panels || []) {
    for (const t of p.targets || []) {
      for (const f of (t.metrics || []).map((m) => m.field).concat((t.bucketAggs || []).map((b) => b.field))) {
        if (!f) continue;
        if (!usage.has(f)) usage.set(f, new Set());
        usage.get(f).add(`${(d.title || '').trim()} → ${p.title}`);
      }
    }
  }
}
for (const [f, users] of [...usage.entries()].sort()) {
  md.push(`| \`${f}\` | ${[...users].slice(0, 4).join('; ')}${users.size > 4 ? ` (+${users.size - 4} more)` : ''} |`);
}
md.push('');

fs.mkdirSync(DOC_DIR, { recursive: true });
fs.writeFileSync(path.join(DOC_DIR, 'DASHBOARD-CATALOG.md'), md.join('\n'));
console.log(`catalog: ${dashes.length} dashboards, ${usage.size} distinct fields`);
console.log('wrote docs/DASHBOARD-CATALOG.md');
